// Builds kit.css for the "Submana Canvas" mockups: every stylesheet in src/app/, the CSS modules with
// their classes prefixed by file name (`Navigation_bar`, like CSS Modules does with hashes, so generic
// names such as .row don't collide), and base.css (what Tailwind and next/font give the app).
//
// Usage: node docs/design/canvas/build-kit.mjs [out file]   (default: kit.css in the OS temp folder)
// Then upload the file as an asset of the canvas and point the artboards' <link> at the new url
// (see AGENTS.md, "Mockups").

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { basename, dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..", "..", "..");
const out = resolve(process.argv[2] ?? join(tmpdir(), "kit.css"));

// globals.css first: it defines the theme tokens the others use.
const APP = ["globals.css", ...readdirSync(join(root, "src/app")).filter((f) => f.endsWith(".css") && f !== "globals.css").sort()];
const MODULES = [
  "src/components/Navigation.module.css",
  "src/components/notifications/NotificationsInbox.module.css",
  "src/components/notifications/NotificationBell.module.css",
];

/** Drops what only the Tailwind build understands: @import, @custom-variant and @theme blocks. */
function stripTailwind(css) {
  let result = css.replace(/^@import\s+[^;]+;\s*$/gm, "").replace(/^@custom-variant\s+[^;]+;\s*$/gm, "");
  for (let start = result.search(/@theme\b/); start !== -1; start = result.search(/@theme\b/)) {
    let depth = 0;
    let end = result.indexOf("{", start);
    for (; end < result.length; end++) {
      if (result[end] === "{") depth++;
      else if (result[end] === "}" && --depth === 0) break;
    }
    result = result.slice(0, start) + result.slice(end + 1);
  }
  return result;
}

/** Prefixes the class selectors of every rule; declarations, @-rule preludes and comments stay as they are. */
function prefixClasses(css, prefix) {
  let result = "";
  let depthInDecl = 0;
  let buffer = "";
  for (let i = 0; i < css.length; i++) {
    const ch = css[i];
    if (ch === "/" && css[i + 1] === "*") {
      const end = css.indexOf("*/", i + 2);
      const stop = end === -1 ? css.length : end + 2;
      buffer += css.slice(i, stop);
      i = stop - 1;
      continue;
    }
    if (ch === "{") {
      const head = buffer;
      const isAtRule = head.trim().startsWith("@");
      const isKeyframeStep = /^\s*(from|to|\d+%)/.test(head.replace(/\/\*[\s\S]*?\*\//g, ""));
      result += isAtRule || isKeyframeStep || depthInDecl > 0 ? head : head.replace(/\.(-?[a-zA-Z_][\w-]*)/g, `.${prefix}_$1`);
      result += ch;
      buffer = "";
      // Inside @media/@supports the next block is still a rule list; elsewhere it's declarations.
      if (!isAtRule || /^@(keyframes|font-face)/.test(head.trim())) depthInDecl++;
      continue;
    }
    if (ch === "}") {
      result += buffer + ch;
      buffer = "";
      if (depthInDecl > 0) depthInDecl--;
      continue;
    }
    buffer += ch;
  }
  return result + buffer;
}

let css = "/* Generated by docs/design/canvas/build-kit.mjs. Don't edit: change the app's CSS and run it again. */\n";
for (const file of APP) css += `\n/* ── src/app/${file} ── */\n` + stripTailwind(readFileSync(join(root, "src/app", file), "utf8")) + "\n";
for (const file of MODULES) {
  const prefix = basename(file).replace(".module.css", "");
  css += `\n/* ── ${file} → .${prefix}_* ── */\n` + prefixClasses(readFileSync(join(root, file), "utf8"), prefix) + "\n";
}
css += "\n/* ── docs/design/canvas/base.css ── */\n" + readFileSync(join(here, "base.css"), "utf8");
writeFileSync(out, css);
console.log(`${out}: ${APP.length} app stylesheets, ${MODULES.length} modules, ${Math.round(css.length / 1024)} KB`);
